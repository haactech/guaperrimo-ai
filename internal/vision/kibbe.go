const KibbeReference = `FAMILIAS KIBBE — REFERENCIA (5 familias simplificadas)

DRAMATIC: Angular, vertical, bordes definidos
  Favorece: líneas rectas largas, siluetas columna, telas estructuradas, minimalismo
  Desfavorece: volantes, prints pequeños, ropa oversized sin estructura

NATURAL: Amplio, atlético, bordes suaves
  Favorece: ropa relajada pero con forma, telas naturales, capas, siluetas descontraídas
  Desfavorece: ropa muy ajustada, muy estructurada, demasiado formal

CLASSIC: Simétrico, moderado, equilibrado
  Favorece: cortes limpios, proporciones balanceadas, telas peso medio, simplicidad
  Desfavorece: extremos (muy oversize, muy ajustado, muy estampado)

GAMINE: Compacto, mezcla de ángulos y curvas
  Favorece: líneas cortas, contrastes, prints geométricos, detalles
  Desfavorece: ropa fluida larga, siluetas muy sueltas

ROMANTIC: Curvas suaves, redondeado
  Favorece: telas fluidas, cintura definida, drapeado, texturas suaves
  Desfavorece: líneas muy rectas, telas rígidas, cortes boxy

INSTRUCCIONES DE ANÁLISIS:
1. Observa hombros (angulares = Dramatic, anchos = Natural, equilibrados = Classic)
2. Observa silueta general (recta = Dramatic/Natural, curva = Romantic, compacta = Gamine)
3. La ropa encima puede ocultar líneas — estima la familia amplia, no el subtipo
4. Asigna familia con nivel de confianza (low/medium/high)
5. Si la foto no muestra cuerpo completo, usa confianza "low"

EVALUACIÓN DE FIT (1-10):
- ¿Las costuras de los hombros caen donde deben?
- ¿El largo de mangas y pantalón es correcto?
- ¿Hay exceso de tela o tensión visible?
- ¿La prenda sigue la forma del cuerpo o la distorsiona?

EVALUACIÓN DE PROPORCIÓN (1-10):
- ¿Hay balance visual entre parte superior e inferior?
- ¿Se respeta alguna regla de proporción (tercios, 60/40)?
- ¿El punto de corte visual (cinturón, dobladillo, etc.) favorece?

EVALUACIÓN DE ARMONÍA DE LÍNEAS (1-10):
- ¿Las líneas de la ropa acompañan las líneas naturales del cuerpo?
- ¿La estructura de las prendas es coherente con la familia estimada?`
